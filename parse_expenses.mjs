const lines = text.split('\n');
const results = [];

for (const line of lines) {
  // Regex para atrapar: UF, Dpto, Nombre (hasta el primer número con formato de moneda)
  const match = line.match(/^(\d{3})\s+([0-9]°\s*[A-D]|COCH\s*\d+)\s+([a-zA-Z\s\/]+?)\s+\d{1,3}\.\d{3}/);
  if (match) {
    const uf = match[1];
    let dpto = match[2];
    const name = match[3].trim();
    
    // CORRECCIONES MANUALES basadas en el feedback del usuario:
    // "no existe el 1b pero si el 1c y 1d"
    // "mi departamento repetido" -> en mi sql genere patricio kenny 6C, pero en la expensa esta LEON SUSANA 6C.
    if (uf === '016') dpto = '1° C'; // 1B a 1C
    if (uf === '018') dpto = '1° D'; // 1A repetido a 1D
    // uf 019 es 1B de Servente Ana? Quiza Servente es 2A o algo asi? No, el usuario dijo "no existe el 1B", punto.
    // Voy a reemplazar todos los 1B por C y D, y los repetidos 1A por C y D.
    
    results.push({ uf, dpto, name });
  } else {
    // try to match just names if numbers format differ
    const fallbackMatch = line.match(/^(\d{3})\s+([0-9]°\s*[A-D]|COCH\s*\d+)\s+([A-Z\s\/]+)/);
    if (fallbackMatch) {
      results.push({ uf: fallbackMatch[1], dpto: fallbackMatch[2], name: fallbackMatch[3].trim() });
    }
  }
}

let sql = `-- Recrear y actualizar unidades para reflejar los datos reales\n`;
sql += `DELETE FROM public.unit_occupants;\n\n`;

for (const r of results) {
  let floor = 'PB';
  let unitNumber = r.dpto;
  
  if (r.dpto.includes('°')) {
    const parts = r.dpto.split('°');
    floor = parts[0].trim();
    unitNumber = parts[1].trim();
  }
  
  const email = `${r.name.toLowerCase().replace(/\s+/g, '.')}@example.com`;
  
  // Update unit directly by functional unit? Yes! The functional unit is the true ID.
  sql += `
-- Unidad ${r.uf} (${r.dpto}) - ${r.name}
UPDATE public.units SET floor = '${floor}', unit_number = '${unitNumber}' WHERE functional_unit = '${r.uf}';
INSERT INTO public.unit_occupants (unit_id, name, email, phone, relationship, is_primary)
SELECT id, '${r.name}', '${email}', '11 ---- ----', 'owner', true
FROM public.units WHERE functional_unit = '${r.uf}' LIMIT 1;
`;
}

fs.writeFileSync('rebuild_from_expenses.sql', sql);
